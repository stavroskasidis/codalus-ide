// Compiles SVG icons into C# that builds Avalonia geometries (D24, M34a). An MSBuild inline task
// (RoslynCodeTaskFactory, see eng/icons/FluentIcons.targets), so it targets netstandard2.0 and plain C#.
// Each icon becomes a method that draws its paths through a StreamGeometryContext: the shell never parses SVG or
// path data at runtime, and stays Native AOT clean. Only <svg> with <path d="…"> children is accepted (the
// Fluent UI System Icons' format); anything else fails the build, so a new icon can't silently render wrong.
using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using System.Xml.Linq;
using Microsoft.Build.Framework;
using Microsoft.Build.Utilities;

public sealed class CompileFluentIcons : Task
{
    [Required]
    public ITaskItem[] Icons { get; set; }

    [Required]
    public string OutputFile { get; set; }

    public override bool Execute()
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/> by eng/icons/CompileFluentIcons.cs from src/DaedalusStudio.Shell/Icons/Fluent/*.svg.");
        sb.AppendLine("// Fluent UI System Icons, Copyright (c) 2020 Microsoft Corporation, MIT licence (THIRD-PARTY-NOTICES.md).");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using Avalonia;");
        sb.AppendLine("using Avalonia.Media;");
        sb.AppendLine();
        sb.AppendLine("namespace DaedalusStudio.Shell.Controls;");
        sb.AppendLine();
        sb.AppendLine("internal static class FluentIcons");
        sb.AppendLine("{");

        var methods = new StringBuilder();
        var names = new List<KeyValuePair<string, double>>();
        foreach (var item in Icons.OrderBy(i => i.ItemSpec, StringComparer.Ordinal))
        {
            var name = Path.GetFileNameWithoutExtension(item.ItemSpec);
            try
            {
                var size = Compile(name, File.ReadAllText(item.ItemSpec), methods);
                names.Add(new KeyValuePair<string, double>(name, size));
            }
            catch (Exception ex) when (ex is FormatException || ex is System.Xml.XmlException)
            {
                Log.LogError("{0}: {1}", item.ItemSpec, ex.Message);
            }
        }

        if (Log.HasLoggedErrors)
        {
            return false;
        }

        sb.AppendLine("    /// <summary>The icons' file names (without .svg).</summary>");
        sb.Append("    public static readonly string[] Names = [");
        sb.Append(string.Join(", ", names.Select(n => "\"" + n.Key + "\"")));
        sb.AppendLine("];");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>The design size of an icon (its view box: 16 or 20), or 0 for an unknown name.</summary>");
        sb.AppendLine("    public static double DesignSize(string name) => name switch");
        sb.AppendLine("    {");
        foreach (var pair in names)
        {
            sb.AppendLine("        \"" + pair.Key + "\" => " + Number(pair.Value) + ",");
        }

        sb.AppendLine("        _ => 0,");
        sb.AppendLine("    };");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>A new geometry for an icon, or null for an unknown name.</summary>");
        sb.AppendLine("    public static StreamGeometry? Create(string name) => name switch");
        sb.AppendLine("    {");
        foreach (var pair in names)
        {
            sb.AppendLine("        \"" + pair.Key + "\" => " + MethodName(pair.Key) + "(),");
        }

        sb.AppendLine("        _ => null,");
        sb.AppendLine("    };");
        sb.Append(methods);
        sb.AppendLine("}");

        var text = sb.ToString();
        if (!File.Exists(OutputFile) || File.ReadAllText(OutputFile) != text)
        {
            Directory.CreateDirectory(Path.GetDirectoryName(OutputFile));
            File.WriteAllText(OutputFile, text);
        }

        return true;
    }

    private static double Compile(string name, string svg, StringBuilder methods)
    {
        var root = XDocument.Parse(svg).Root;
        if (root == null || root.Name.LocalName != "svg")
        {
            throw new FormatException("not an <svg> document");
        }

        var viewBox = ((string)root.Attribute("viewBox") ?? string.Empty).Split(new[] { ' ', ',' }, StringSplitOptions.RemoveEmptyEntries);
        if (viewBox.Length != 4 || viewBox[0] != "0" || viewBox[1] != "0" || viewBox[2] != viewBox[3])
        {
            throw new FormatException("expected a square viewBox at the origin");
        }

        var size = double.Parse(viewBox[2], CultureInfo.InvariantCulture);
        methods.AppendLine();
        methods.AppendLine("    private static StreamGeometry " + MethodName(name) + "()");
        methods.AppendLine("    {");
        methods.AppendLine("        var g = new StreamGeometry();");
        methods.AppendLine("        using (var c = g.Open())");
        methods.AppendLine("        {");
        methods.AppendLine("            c.SetFillRule(FillRule.NonZero);");
        foreach (var element in root.Elements())
        {
            if (element.Name.LocalName != "path" || element.Attributes().Any(a => a.Name.LocalName != "d"))
            {
                throw new FormatException("only <path d=\"…\"> elements are supported, found <" + element.Name.LocalName + ">");
            }

            new PathCompiler((string)element.Attribute("d"), methods).Run();
        }

        methods.AppendLine("        }");
        methods.AppendLine();
        methods.AppendLine("        return g;");
        methods.AppendLine("    }");
        return size;
    }

    private static string MethodName(string name)
    {
        var sb = new StringBuilder("Icon_");
        foreach (var ch in name)
        {
            sb.Append(char.IsLetterOrDigit(ch) ? ch : '_');
        }

        return sb.ToString();
    }

    internal static string Number(double value)
    {
        var rounded = Math.Round(value, 4);
        return rounded == 0 ? "0" : rounded.ToString("0.####", CultureInfo.InvariantCulture);
    }

    /// <summary>SVG path data (all commands, relative and absolute, implicit repeats, compact arc flags) to calls.</summary>
    private sealed class PathCompiler
    {
        private readonly string _d;
        private readonly StringBuilder _out;
        private int _pos;
        private double _x;
        private double _y;
        private double _startX;
        private double _startY;
        private double _controlX;
        private double _controlY;
        private char _last;
        private bool _open;

        public PathCompiler(string d, StringBuilder output)
        {
            _d = d ?? string.Empty;
            _out = output;
        }

        public void Run()
        {
            var command = '\0';
            while (true)
            {
                SkipSeparators();
                if (_pos >= _d.Length)
                {
                    break;
                }

                var ch = _d[_pos];
                if (char.IsLetter(ch) && ch != 'e' && ch != 'E')
                {
                    command = ch;
                    _pos++;
                }
                else if (command == '\0')
                {
                    throw new FormatException("path data must start with a command");
                }
                else if (command == 'M')
                {
                    command = 'L';
                }
                else if (command == 'm')
                {
                    command = 'l';
                }
                else if (command == 'Z' || command == 'z')
                {
                    throw new FormatException("numbers after Z");
                }

                Step(command);
            }

            if (_open)
            {
                Emit("c.EndFigure(false);");
            }
        }

        private void Step(char command)
        {
            var relative = char.IsLower(command);
            double ox = relative ? _x : 0, oy = relative ? _y : 0;
            switch (char.ToUpperInvariant(command))
            {
                case 'M':
                {
                    var x = ox + Number();
                    var y = oy + Number();
                    if (_open)
                    {
                        Emit("c.EndFigure(false);");
                    }

                    Emit("c.BeginFigure(" + Point(x, y) + ", true);");
                    _open = true;
                    _x = _startX = x;
                    _y = _startY = y;
                    _last = 'M';
                    return;
                }

                case 'Z':
                    if (_open)
                    {
                        Emit("c.EndFigure(true);");
                    }

                    _open = false;
                    _x = _startX;
                    _y = _startY;
                    _last = 'Z';
                    return;

                case 'L':
                    LineTo(ox + Number(), oy + Number());
                    return;

                case 'H':
                    LineTo(ox + Number(), _y);
                    return;

                case 'V':
                    LineTo(_x, oy + Number());
                    return;

                case 'C':
                {
                    double x1 = ox + Number(), y1 = oy + Number(), x2 = ox + Number(), y2 = oy + Number(), x = ox + Number(), y = oy + Number();
                    Cubic(x1, y1, x2, y2, x, y);
                    return;
                }

                case 'S':
                {
                    double x1 = _last == 'C' ? 2 * _x - _controlX : _x, y1 = _last == 'C' ? 2 * _y - _controlY : _y;
                    double x2 = ox + Number(), y2 = oy + Number(), x = ox + Number(), y = oy + Number();
                    Cubic(x1, y1, x2, y2, x, y);
                    return;
                }

                case 'Q':
                {
                    double x1 = ox + Number(), y1 = oy + Number(), x = ox + Number(), y = oy + Number();
                    Quadratic(x1, y1, x, y);
                    return;
                }

                case 'T':
                {
                    double x1 = _last == 'Q' ? 2 * _x - _controlX : _x, y1 = _last == 'Q' ? 2 * _y - _controlY : _y;
                    double x = ox + Number(), y = oy + Number();
                    Quadratic(x1, y1, x, y);
                    return;
                }

                case 'A':
                {
                    double rx = Math.Abs(Number()), ry = Math.Abs(Number()), rotation = Number();
                    var large = Flag();
                    var sweep = Flag();
                    double x = ox + Number(), y = oy + Number();
                    EnsureFigure();
                    if (rx == 0 || ry == 0)
                    {
                        Emit("c.LineTo(" + Point(x, y) + ");");
                    }
                    else
                    {
                        Emit("c.ArcTo(" + Point(x, y) + ", new Size(" + CompileFluentIcons.Number(rx) + ", " + CompileFluentIcons.Number(ry) + "), "
                            + CompileFluentIcons.Number(rotation) + ", " + (large ? "true" : "false") + ", "
                            + (sweep ? "SweepDirection.Clockwise" : "SweepDirection.CounterClockwise") + ");");
                    }

                    _x = x;
                    _y = y;
                    _last = 'A';
                    return;
                }

                default:
                    throw new FormatException("unsupported path command '" + command + "'");
            }
        }

        private void EnsureFigure()
        {
            if (!_open)
            {
                Emit("c.BeginFigure(" + Point(_x, _y) + ", true);");
                _open = true;
                _startX = _x;
                _startY = _y;
            }
        }

        private void LineTo(double x, double y)
        {
            EnsureFigure();
            Emit("c.LineTo(" + Point(x, y) + ");");
            _x = x;
            _y = y;
            _last = 'L';
        }

        private void Cubic(double x1, double y1, double x2, double y2, double x, double y)
        {
            EnsureFigure();
            Emit("c.CubicBezierTo(" + Point(x1, y1) + ", " + Point(x2, y2) + ", " + Point(x, y) + ");");
            _controlX = x2;
            _controlY = y2;
            _x = x;
            _y = y;
            _last = 'C';
        }

        private void Quadratic(double x1, double y1, double x, double y)
        {
            EnsureFigure();
            Emit("c.QuadraticBezierTo(" + Point(x1, y1) + ", " + Point(x, y) + ");");
            _controlX = x1;
            _controlY = y1;
            _x = x;
            _y = y;
            _last = 'Q';
        }

        private void Emit(string call) => _out.Append("            ").AppendLine(call);

        private static string Point(double x, double y) => "new Point(" + CompileFluentIcons.Number(x) + ", " + CompileFluentIcons.Number(y) + ")";

        private void SkipSeparators()
        {
            while (_pos < _d.Length && (char.IsWhiteSpace(_d[_pos]) || _d[_pos] == ','))
            {
                _pos++;
            }
        }

        private bool Flag()
        {
            SkipSeparators();
            if (_pos < _d.Length && (_d[_pos] == '0' || _d[_pos] == '1'))
            {
                return _d[_pos++] == '1';
            }

            throw new FormatException("expected an arc flag at " + _pos);
        }

        private double Number()
        {
            SkipSeparators();
            var start = _pos;
            if (_pos < _d.Length && (_d[_pos] == '+' || _d[_pos] == '-'))
            {
                _pos++;
            }

            var dot = false;
            var digits = false;
            while (_pos < _d.Length && (char.IsDigit(_d[_pos]) || (_d[_pos] == '.' && !dot)))
            {
                dot |= _d[_pos] == '.';
                digits |= char.IsDigit(_d[_pos]);
                _pos++;
            }

            if (_pos < _d.Length && (_d[_pos] == 'e' || _d[_pos] == 'E') && digits)
            {
                _pos++;
                if (_pos < _d.Length && (_d[_pos] == '+' || _d[_pos] == '-'))
                {
                    _pos++;
                }

                while (_pos < _d.Length && char.IsDigit(_d[_pos]))
                {
                    _pos++;
                }
            }

            if (!digits)
            {
                throw new FormatException("expected a number at " + start);
            }

            return double.Parse(_d.Substring(start, _pos - start), NumberStyles.Float, CultureInfo.InvariantCulture);
        }
    }
}
