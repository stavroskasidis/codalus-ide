// Compiles SVG icons into C# that builds Avalonia geometries (D24, M34a): the Fluent UI System Icons (commands) and
// Material Icon Theme's file-type icons. An MSBuild inline task (RoslynCodeTaskFactory, see eng/icons/Icons.targets),
// so it targets netstandard2.0 and plain C#. Each icon becomes its drawing operations (a string), their numbers and its
// fills' colors (constant data, no allocation), which the generated CompiledIcons.Create replays into geometries: the
// shell never parses SVG or path data at runtime, and stays Native AOT clean. Only <svg>, <g> and <path> with fills
// are accepted; anything else fails the build, so a new icon can't silently render wrong.
// The same parser, built with CODALUS_SVG_CONVERTER into codalus-pluginhost (--compile-icons), converts the SVG icons of
// plugins' icon themes into the same operations at run time, outside the shell (M22b).
#if CODALUS_SVG_CONVERTER
#pragma warning disable
#endif
using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using System.Xml.Linq;
#if !CODALUS_SVG_CONVERTER
using Microsoft.Build.Framework;
using Microsoft.Build.Utilities;
#endif

#if CODALUS_SVG_CONVERTER
internal sealed class CompileIcons
#else
public sealed class CompileIcons : Task
#endif
{
#if !CODALUS_SVG_CONVERTER
    [Required]
    public ITaskItem[] Icons { get; set; }

    [Required]
    public string OutputFile { get; set; }

    public override bool Execute()
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/> by eng/icons/CompileIcons.cs from src/Codalus.Shell/Icons/{Fluent,Material}/*.svg.");
        sb.AppendLine("// Fluent UI System Icons, Copyright (c) 2020 Microsoft Corporation; Material Icon Theme, Copyright (c) 2025 Material Extensions;");
        sb.AppendLine("// both MIT (THIRD-PARTY-NOTICES.md).");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using Avalonia;");
        sb.AppendLine("using Avalonia.Media;");
        sb.AppendLine();
        sb.AppendLine("namespace Codalus.Shell.Controls;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>One fill of a compiled icon: its geometry and color (0: the icon's foreground).</summary>");
        sb.AppendLine("internal sealed record IconLayer(StreamGeometry Geometry, uint Color);");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// The icons as drawing operations (F/f = a new fill, nonzero or even-odd, with the next color; M = begin a figure;");
        sb.AppendLine("/// L, C, Q, A = line, cubic, quadratic, arc; Z = close; E = end open) and their numbers, parsed from the SVGs at");
        sb.AppendLine("/// build time; <see cref=\"Create\"/> replays them into geometries.");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("internal static class CompiledIcons");
        sb.AppendLine("{");

        var data = new StringBuilder();
        var names = new List<KeyValuePair<string, double>>();
        foreach (var item in Icons.OrderBy(i => Path.GetFileName(i.ItemSpec), StringComparer.Ordinal))
        {
            var name = Path.GetFileNameWithoutExtension(item.ItemSpec);
            if (names.Any(n => n.Key == name))
            {
                Log.LogError("{0}: another icon has the name {1}", item.ItemSpec, name);
                continue;
            }

            try
            {
                var size = Compile(name, File.ReadAllText(item.ItemSpec), data);
                names.Add(new KeyValuePair<string, double>(name, size));
            }
            catch (Exception ex) when (ex is FormatException || ex is System.Xml.XmlException)
            {
                Log.LogError("{0}: {1}", item.ItemSpec, ex.Message);
            }
        }

        if (Log.HasLoggedErrors)
        {
            return false;
        }

        sb.AppendLine("    /// <summary>The icons' file names (without .svg).</summary>");
        sb.Append("    public static readonly string[] Names = [");
        sb.Append(string.Join(", ", names.Select(n => "\"" + n.Key + "\"")));
        sb.AppendLine("];");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>The design size of an icon (its view box's width), or 0 for an unknown name.</summary>");
        sb.AppendLine("    public static double DesignSize(string name) => name switch");
        sb.AppendLine("    {");
        foreach (var pair in names)
        {
            sb.AppendLine("        \"" + pair.Key + "\" => " + Number(pair.Value) + ",");
        }

        sb.AppendLine("        _ => 0,");
        sb.AppendLine("    };");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>New geometries for an icon, or null for an unknown name.</summary>");
        sb.AppendLine("    public static IconLayer[]? Create(string name) => name switch");
        sb.AppendLine("    {");
        foreach (var pair in names)
        {
            sb.AppendLine("        \"" + pair.Key + "\" => Build(" + MemberName("Ops_", pair.Key) + ", " + MemberName("Data_", pair.Key) + ", " + MemberName("Colors_", pair.Key) + "),");
        }

        sb.AppendLine("        _ => null,");
        sb.AppendLine("    };");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>Replays drawing operations into geometries (also those of icon themes' SVG icons, converted outside the shell).</summary>");
        sb.AppendLine("    internal static IconLayer[] Build(string ops, ReadOnlySpan<float> n, ReadOnlySpan<uint> colors)");
        sb.AppendLine("    {");
        sb.AppendLine("        var layers = new List<IconLayer>();");
        sb.AppendLine("        StreamGeometry? geometry = null;");
        sb.AppendLine("        StreamGeometryContext? c = null;");
        sb.AppendLine("        var i = 0;");
        sb.AppendLine("        foreach (var op in ops)");
        sb.AppendLine("        {");
        sb.AppendLine("            switch (op)");
        sb.AppendLine("            {");
        sb.AppendLine("                case 'F' or 'f':");
        sb.AppendLine("                    c?.Dispose();");
        sb.AppendLine("                    geometry = new StreamGeometry();");
        sb.AppendLine("                    c = geometry.Open();");
        sb.AppendLine("                    c.SetFillRule(op == 'F' ? FillRule.NonZero : FillRule.EvenOdd);");
        sb.AppendLine("                    layers.Add(new IconLayer(geometry, colors[layers.Count]));");
        sb.AppendLine("                    break;");
        sb.AppendLine("                case 'M': c!.BeginFigure(new Point(n[i], n[i + 1]), true); i += 2; break;");
        sb.AppendLine("                case 'L': c!.LineTo(new Point(n[i], n[i + 1])); i += 2; break;");
        sb.AppendLine("                case 'C': c!.CubicBezierTo(new Point(n[i], n[i + 1]), new Point(n[i + 2], n[i + 3]), new Point(n[i + 4], n[i + 5])); i += 6; break;");
        sb.AppendLine("                case 'Q': c!.QuadraticBezierTo(new Point(n[i], n[i + 1]), new Point(n[i + 2], n[i + 3])); i += 4; break;");
        sb.AppendLine("                case 'A': c!.ArcTo(new Point(n[i], n[i + 1]), new Size(n[i + 2], n[i + 3]), n[i + 4], n[i + 5] != 0, n[i + 6] != 0 ? SweepDirection.Clockwise : SweepDirection.CounterClockwise); i += 7; break;");
        sb.AppendLine("                case 'Z': c!.EndFigure(true); break;");
        sb.AppendLine("                default: c!.EndFigure(false); break;");
        sb.AppendLine("            }");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        c?.Dispose();");
        sb.AppendLine("        return [.. layers];");
        sb.AppendLine("    }");
        sb.Append(data);
        sb.AppendLine("}");

        var text = sb.ToString();
        if (!File.Exists(OutputFile) || File.ReadAllText(OutputFile) != text)
        {
            Directory.CreateDirectory(Path.GetDirectoryName(OutputFile));
            File.WriteAllText(OutputFile, text);
        }

        return true;
    }

    private static double Compile(string name, string svg, StringBuilder data)
    {
        var ops = new StringBuilder();
        var numbers = new List<double>();
        var colors = new List<uint>();
        var size = Parse(svg, ops, numbers, colors);
        data.AppendLine();
        data.AppendLine("    private const string " + MemberName("Ops_", name) + " = \"" + ops + "\";");
        data.AppendLine();
        data.AppendLine("    private static ReadOnlySpan<float> " + MemberName("Data_", name) + " => [" + string.Join(", ", numbers.Select(v => Number(v) + "f")) + "];");
        data.AppendLine();
        data.AppendLine("    private static ReadOnlySpan<uint> " + MemberName("Colors_", name) + " => [" + string.Join(", ", colors.Select(c => "0x" + c.ToString("X8", CultureInfo.InvariantCulture))) + "];");
        return size;
    }
#endif

    /// <summary>An icon's drawing operations, numbers and fill colors; returns its design size (the view box's width).</summary>
    internal static double Parse(string svg, StringBuilder ops, List<double> numbers, List<uint> colors)
    {
        var root = XDocument.Parse(svg).Root;
        if (root == null || root.Name.LocalName != "svg")
        {
            throw new FormatException("not an <svg> document");
        }

        var viewBox = ((string)root.Attribute("viewBox") ?? string.Empty).Split(new[] { ' ', ',' }, StringSplitOptions.RemoveEmptyEntries)
            .Select(v => double.Parse(v, CultureInfo.InvariantCulture)).ToArray();
        if (viewBox.Length != 4 || viewBox[2] != viewBox[3] || viewBox[2] <= 0)
        {
            throw new FormatException("expected a square viewBox");
        }

        Walk(root, Fill(root, null), ops, numbers, colors, -viewBox[0], -viewBox[1]);
        if (colors.Count == 0)
        {
            throw new FormatException("nothing to draw");
        }

        return viewBox[2];
    }

    /// <summary>
    /// The paths under <paramref name="parent"/> in document order. Each path is a fill of its own color (its
    /// <c>fill</c>, or its group's, or the document's; none means the foreground); consecutive paths of one color share
    /// a fill. Groups only carry fills; anything else fails, so an unsupported icon is caught at build time.
    /// </summary>
    private static void Walk(XElement parent, string inherited, StringBuilder ops, List<double> numbers, List<uint> colors, double tx, double ty)
    {
        foreach (var element in parent.Elements())
        {
            var local = element.Name.LocalName;
            foreach (var attribute in element.Attributes())
            {
                if (attribute.IsNamespaceDeclaration || attribute.Name.LocalName is "id" or "fill" or "fill-rule" or "clip-rule" || (local == "path" && attribute.Name.LocalName == "d"))
                {
                    continue;
                }

                throw new FormatException("unsupported attribute " + attribute.Name.LocalName + " on <" + local + ">");
            }

            if (local == "g")
            {
                Walk(element, Fill(element, inherited), ops, numbers, colors, tx, ty);
                continue;
            }

            if (local != "path")
            {
                throw new FormatException("only <path> and <g> elements are supported, found <" + local + ">");
            }

            var fill = Fill(element, inherited);
            if (fill == "none")
            {
                continue;
            }

            var color = Color(fill);
            var rule = (string)element.Attribute("fill-rule") == "evenodd" ? 'f' : 'F';
            if (colors.Count == 0 || colors[colors.Count - 1] != color || LastFill(ops) != rule)
            {
                ops.Append(rule);
                colors.Add(color);
            }

            new PathCompiler((string)element.Attribute("d"), ops, numbers, tx, ty).Run();
        }
    }

    private static char LastFill(StringBuilder ops)
    {
        for (var i = ops.Length - 1; i >= 0; i--)
        {
            if (ops[i] == 'F' || ops[i] == 'f')
            {
                return ops[i];
            }
        }

        return '\0';
    }

    private static string Fill(XElement element, string inherited) => (string)element.Attribute("fill") ?? inherited;

    /// <summary>A fill color as ARGB; 0 (no fill given) is the icon's foreground.</summary>
    private static uint Color(string fill)
    {
        if (fill == null || fill == "currentColor")
        {
            return 0;
        }

        if (fill.Length > 0 && fill[0] == '#')
        {
            var hex = fill.Substring(1);
            if (hex.Length == 3)
            {
                hex = new string(new[] { hex[0], hex[0], hex[1], hex[1], hex[2], hex[2] });
            }

            if (hex.Length == 6)
            {
                return 0xFF000000u | uint.Parse(hex, NumberStyles.HexNumber, CultureInfo.InvariantCulture);
            }

            if (hex.Length == 8)
            {
                var rgba = uint.Parse(hex, NumberStyles.HexNumber, CultureInfo.InvariantCulture);
                return (rgba << 24) | (rgba >> 8);
            }
        }

        throw new FormatException("unsupported fill " + fill);
    }

    private static string MemberName(string prefix, string name)
    {
        var sb = new StringBuilder(prefix);
        foreach (var ch in name)
        {
            sb.Append(char.IsLetterOrDigit(ch) ? ch : '_');
        }

        return sb.ToString();
    }

    internal static string Number(double value)
    {
        var rounded = Math.Round(value, 4);
        return rounded == 0 ? "0" : rounded.ToString("0.####", CultureInfo.InvariantCulture);
    }

    /// <summary>SVG path data (all commands, relative and absolute, implicit repeats, compact arc flags) to calls.</summary>
    private sealed class PathCompiler
    {
        private readonly string _d;
        private readonly StringBuilder _ops;
        private readonly List<double> _numbers;
        private int _pos;
        private double _x;
        private double _y;
        private double _startX;
        private double _startY;
        private double _controlX;
        private double _controlY;
        private char _last;
        private bool _open;
        private readonly double _tx;
        private readonly double _ty;

        public PathCompiler(string d, StringBuilder ops, List<double> numbers, double tx, double ty)
        {
            _d = d ?? string.Empty;
            _ops = ops;
            _numbers = numbers;
            _tx = tx;
            _ty = ty;
        }

        public void Run()
        {
            var command = '\0';
            while (true)
            {
                SkipSeparators();
                if (_pos >= _d.Length)
                {
                    break;
                }

                var ch = _d[_pos];
                if (char.IsLetter(ch) && ch != 'e' && ch != 'E')
                {
                    command = ch;
                    _pos++;
                }
                else if (command == '\0')
                {
                    throw new FormatException("path data must start with a command");
                }
                else if (command == 'M')
                {
                    command = 'L';
                }
                else if (command == 'm')
                {
                    command = 'l';
                }
                else if (command == 'Z' || command == 'z')
                {
                    throw new FormatException("numbers after Z");
                }

                Step(command);
            }

            if (_open)
            {
                Op('E');
            }
        }

        private void Step(char command)
        {
            var relative = char.IsLower(command);
            double ox = relative ? _x : 0, oy = relative ? _y : 0;
            switch (char.ToUpperInvariant(command))
            {
                case 'M':
                {
                    var x = ox + Number();
                    var y = oy + Number();
                    if (_open)
                    {
                        Op('E');
                    }

                    Op('M', x, y);
                    _open = true;
                    _x = _startX = x;
                    _y = _startY = y;
                    _last = 'M';
                    return;
                }

                case 'Z':
                    if (_open)
                    {
                        Op('Z');
                    }

                    _open = false;
                    _x = _startX;
                    _y = _startY;
                    _last = 'Z';
                    return;

                case 'L':
                    LineTo(ox + Number(), oy + Number());
                    return;

                case 'H':
                    LineTo(ox + Number(), _y);
                    return;

                case 'V':
                    LineTo(_x, oy + Number());
                    return;

                case 'C':
                {
                    double x1 = ox + Number(), y1 = oy + Number(), x2 = ox + Number(), y2 = oy + Number(), x = ox + Number(), y = oy + Number();
                    Cubic(x1, y1, x2, y2, x, y);
                    return;
                }

                case 'S':
                {
                    double x1 = _last == 'C' ? 2 * _x - _controlX : _x, y1 = _last == 'C' ? 2 * _y - _controlY : _y;
                    double x2 = ox + Number(), y2 = oy + Number(), x = ox + Number(), y = oy + Number();
                    Cubic(x1, y1, x2, y2, x, y);
                    return;
                }

                case 'Q':
                {
                    double x1 = ox + Number(), y1 = oy + Number(), x = ox + Number(), y = oy + Number();
                    Quadratic(x1, y1, x, y);
                    return;
                }

                case 'T':
                {
                    double x1 = _last == 'Q' ? 2 * _x - _controlX : _x, y1 = _last == 'Q' ? 2 * _y - _controlY : _y;
                    double x = ox + Number(), y = oy + Number();
                    Quadratic(x1, y1, x, y);
                    return;
                }

                case 'A':
                {
                    double rx = Math.Abs(Number()), ry = Math.Abs(Number()), rotation = Number();
                    var large = Flag();
                    var sweep = Flag();
                    double x = ox + Number(), y = oy + Number();
                    EnsureFigure();
                    if (rx == 0 || ry == 0)
                    {
                        Op('L', x, y);
                    }
                    else
                    {
                        Op('A', x, y, rx, ry, rotation, large ? 1 : 0, sweep ? 1 : 0);
                    }

                    _x = x;
                    _y = y;
                    _last = 'A';
                    return;
                }

                default:
                    throw new FormatException("unsupported path command '" + command + "'");
            }
        }

        private void EnsureFigure()
        {
            if (!_open)
            {
                Op('M', _x, _y);
                _open = true;
                _startX = _x;
                _startY = _y;
            }
        }

        private void LineTo(double x, double y)
        {
            EnsureFigure();
            Op('L', x, y);
            _x = x;
            _y = y;
            _last = 'L';
        }

        private void Cubic(double x1, double y1, double x2, double y2, double x, double y)
        {
            EnsureFigure();
            Op('C', x1, y1, x2, y2, x, y);
            _controlX = x2;
            _controlY = y2;
            _x = x;
            _y = y;
            _last = 'C';
        }

        private void Quadratic(double x1, double y1, double x, double y)
        {
            EnsureFigure();
            Op('Q', x1, y1, x, y);
            _controlX = x1;
            _controlY = y1;
            _x = x;
            _y = y;
            _last = 'Q';
        }

        /// <summary>An operation and its numbers; its points move by the view box's origin (an arc's radii don't).</summary>
        private void Op(char op, params double[] numbers)
        {
            _ops.Append(op);
            var points = op == 'A' ? 1 : numbers.Length / 2;
            for (var i = 0; i < numbers.Length; i++)
            {
                _numbers.Add(i < points * 2 ? numbers[i] + (i % 2 == 0 ? _tx : _ty) : numbers[i]);
            }
        }

        

        private void SkipSeparators()
        {
            while (_pos < _d.Length && (char.IsWhiteSpace(_d[_pos]) || _d[_pos] == ','))
            {
                _pos++;
            }
        }

        private bool Flag()
        {
            SkipSeparators();
            if (_pos < _d.Length && (_d[_pos] == '0' || _d[_pos] == '1'))
            {
                return _d[_pos++] == '1';
            }

            throw new FormatException("expected an arc flag at " + _pos);
        }

        private double Number()
        {
            SkipSeparators();
            var start = _pos;
            if (_pos < _d.Length && (_d[_pos] == '+' || _d[_pos] == '-'))
            {
                _pos++;
            }

            var dot = false;
            var digits = false;
            while (_pos < _d.Length && (char.IsDigit(_d[_pos]) || (_d[_pos] == '.' && !dot)))
            {
                dot |= _d[_pos] == '.';
                digits |= char.IsDigit(_d[_pos]);
                _pos++;
            }

            if (_pos < _d.Length && (_d[_pos] == 'e' || _d[_pos] == 'E') && digits)
            {
                _pos++;
                if (_pos < _d.Length && (_d[_pos] == '+' || _d[_pos] == '-'))
                {
                    _pos++;
                }

                while (_pos < _d.Length && char.IsDigit(_d[_pos]))
                {
                    _pos++;
                }
            }

            if (!digits)
            {
                throw new FormatException("expected a number at " + start);
            }

            return double.Parse(_d.Substring(start, _pos - start), NumberStyles.Float, CultureInfo.InvariantCulture);
        }
    }
