using System.Globalization;
using System.Text;
using System.Xml;
using System.Xml.Linq;

namespace Codalus.Workbench.CustomTools;

/// <summary>
/// The resources custom tools (ADR 0035): <c>ResXFileCodeGenerator</c> and <c>PublicResXFileCodeGenerator</c>. A
/// <c>.resx</c> file's strongly typed class, in the shape <c>StronglyTypedResourceBuilder</c> gives it (Visual Studio's
/// generator): a <c>ResourceManager</c>, a <c>Culture</c>, and a property per resource (strings as <c>string</c>, other
/// resources as their type through <c>GetObject</c>).
/// </summary>
public static class ResXGenerator
{
    public const string Internal = "ResXFileCodeGenerator";
    public const string Public = "PublicResXFileCodeGenerator";

    /// <summary>A resource of a <c>.resx</c> file: its name, value (strings), comment and type (null for strings).</summary>
    public sealed record Resource(string Name, string? Value, string? Comment, string? Type);

    /// <summary>The resources of a <c>.resx</c> file, in file order.</summary>
    public static IReadOnlyList<Resource> Read(string resx)
    {
        var document = XDocument.Parse(resx);
        var resources = new List<Resource>();
        foreach (var data in document.Root?.Elements("data") ?? [])
        {
            var name = (string?)data.Attribute("name");
            if (string.IsNullOrEmpty(name))
            {
                continue;
            }

            var type = (string?)data.Attribute("type");
            var mime = (string?)data.Attribute("mimetype");
            var value = (string?)data.Element("value");
            var comment = (string?)data.Element("comment");
            if (type is null && mime is null)
            {
                resources.Add(new Resource(name, value ?? string.Empty, comment, null));
            }
            else if (type?.StartsWith("System.Resources.ResXFileRef", StringComparison.Ordinal) == true && value?.Split(';') is [_, var fileType, ..])
            {
                resources.Add(new Resource(name, null, comment, TypeName(fileType)));
            }
            else if (type is not null && TypeName(type) is { } typeName && typeName != "System.String")
            {
                resources.Add(new Resource(name, null, comment, typeName));
            }
            else if (type is not null)
            {
                resources.Add(new Resource(name, value ?? string.Empty, comment, null));
            }
            else
            {
                resources.Add(new Resource(name, null, comment, "System.Object"));
            }
        }

        return resources;
    }

    /// <summary>
    /// The class for <paramref name="resx"/>: <paramref name="className"/> in <paramref name="namespace"/>, public with
    /// <paramref name="isPublic"/>, reading the manifest resource <paramref name="resourceName"/>.
    /// </summary>
    public static string Generate(string resx, string className, string @namespace, string resourceName, bool isPublic)
    {
        var access = isPublic ? "public" : "internal";
        var code = new StringBuilder();
        code.Append("""
            //------------------------------------------------------------------------------
            // <auto-generated>
            //     This code was generated by a tool.
            //
            //     Changes to this file may cause incorrect behavior and will be lost if
            //     the code is regenerated.
            // </auto-generated>
            //------------------------------------------------------------------------------


            """);
        var indent = string.Empty;
        if (@namespace.Length > 0)
        {
            code.Append("namespace ").Append(@namespace).Append(" {\n");
            indent = "    ";
        }

        void Line(string text = "") => code.Append(text.Length == 0 ? string.Empty : indent).Append(text).Append('\n');
        Line("using System;");
        Line();
        Line();
        Line("/// <summary>");
        Line("///   A strongly-typed resource class, for looking up localized strings, etc.");
        Line("/// </summary>");
        Line("[global::System.CodeDom.Compiler.GeneratedCodeAttribute(\"System.Resources.Tools.StronglyTypedResourceBuilder\", \"17.0.0.0\")]");
        Line("[global::System.Diagnostics.DebuggerNonUserCodeAttribute()]");
        Line("[global::System.Runtime.CompilerServices.CompilerGeneratedAttribute()]");
        Line($"{access} class {className} {{");
        Line("    ");
        Line("    private static global::System.Resources.ResourceManager resourceMan;");
        Line("    ");
        Line("    private static global::System.Globalization.CultureInfo resourceCulture;");
        Line("    ");
        Line("    [global::System.Diagnostics.CodeAnalysis.SuppressMessageAttribute(\"Microsoft.Performance\", \"CA1811:AvoidUncalledPrivateCode\")]");
        Line($"    internal {className}() {{");
        Line("    }");
        Line("    ");
        Line("    /// <summary>");
        Line("    ///   Returns the cached ResourceManager instance used by this class.");
        Line("    /// </summary>");
        Line("    [global::System.ComponentModel.EditorBrowsableAttribute(global::System.ComponentModel.EditorBrowsableState.Advanced)]");
        Line($"    {access} static global::System.Resources.ResourceManager ResourceManager {{");
        Line("        get {");
        Line("            if (object.ReferenceEquals(resourceMan, null)) {");
        Line($"                global::System.Resources.ResourceManager temp = new global::System.Resources.ResourceManager(\"{resourceName}\", typeof({className}).Assembly);");
        Line("                resourceMan = temp;");
        Line("            }");
        Line("            return resourceMan;");
        Line("        }");
        Line("    }");
        Line("    ");
        Line("    /// <summary>");
        Line("    ///   Overrides the current thread's CurrentUICulture property for all");
        Line("    ///   resource lookups using this strongly typed resource class.");
        Line("    /// </summary>");
        Line("    [global::System.ComponentModel.EditorBrowsableAttribute(global::System.ComponentModel.EditorBrowsableState.Advanced)]");
        Line($"    {access} static global::System.Globalization.CultureInfo Culture {{");
        Line("        get {");
        Line("            return resourceCulture;");
        Line("        }");
        Line("        set {");
        Line("            resourceCulture = value;");
        Line("        }");
        Line("    }");
        foreach (var resource in Read(resx).OrderBy(r => r.Name, StringComparer.Ordinal))
        {
            var property = Identifier(resource.Name);
            if (property == className || property is "ResourceManager" or "Culture")
            {
                continue;
            }

            Line("    ");
            Line("    /// <summary>");
            if (resource.Type is null)
            {
                Line($"    ///   Looks up a localized string similar to {Summary(resource.Value ?? string.Empty)}.");
            }
            else
            {
                Line($"    ///   Looks up a localized resource of type {Escape(resource.Type)}.");
            }

            Line("    /// </summary>");
            if (resource.Type is null)
            {
                Line($"    {access} static string {property} {{");
                Line("        get {");
                Line($"            return ResourceManager.GetString(\"{resource.Name}\", resourceCulture);");
            }
            else
            {
                Line($"    {access} static global::{resource.Type} {property} {{");
                Line("        get {");
                Line($"            object obj = ResourceManager.GetObject(\"{resource.Name}\", resourceCulture);");
                Line($"            return ((global::{resource.Type})(obj));");
            }

            Line("        }");
            Line("    }");
        }

        Line("}");
        if (@namespace.Length > 0)
        {
            code.Append("}\n");
        }

        return code.ToString();
    }

    /// <summary>The type name of an assembly-qualified type (<c>System.Drawing.Bitmap, System.Drawing</c> → <c>System.Drawing.Bitmap</c>).</summary>
    private static string? TypeName(string assemblyQualified) =>
        assemblyQualified.Split(',')[0].Trim() is { Length: > 0 } name ? name.Replace('+', '.') : null;

    /// <summary>A valid C# identifier for a resource name, as StronglyTypedResourceBuilder makes it.</summary>
    public static string Identifier(string name)
    {
        var text = new string([.. name.Select(c => char.IsLetterOrDigit(c) || c == '_' ? c : '_')]);
        return text.Length == 0 || char.IsDigit(text[0]) ? "_" + text : text;
    }

    /// <summary>The value as StronglyTypedResourceBuilder quotes it in the summary: XML-escaped, the first 512 characters, line breaks kept as comment lines.</summary>
    private static string Summary(string value)
    {
        var text = value.Length > 512 ? value[..512] + " [rest of string was truncated]" : value;
        return Escape(text).ReplaceLineEndings("\n").Replace("\n", "\n    ///", StringComparison.Ordinal);
    }

    private static string Escape(string text)
    {
        var builder = new StringBuilder();
        using (var writer = XmlWriter.Create(builder, new XmlWriterSettings { ConformanceLevel = ConformanceLevel.Fragment }))
        {
            writer.WriteString(text);
        }

        return builder.ToString();
    }

    /// <summary>The manifest resource name MSBuild gives a <c>.resx</c>: the root namespace, the folders, and the file's name.</summary>
    public static string ManifestResourceName(string rootNamespace, string projectDirectory, string resx)
    {
        var relative = Path.GetRelativePath(projectDirectory, Path.ChangeExtension(resx, null)!);
        var parts = relative.Split(['\\', '/'], StringSplitOptions.RemoveEmptyEntries).Select((p, i) => i == relative.Split(['\\', '/'], StringSplitOptions.RemoveEmptyEntries).Length - 1 ? p : p.Replace(' ', '_'));
        return string.Join('.', new[] { rootNamespace }.Where(r => r.Length > 0).Concat(parts));
    }

    internal static string Invariant(int value) => value.ToString(CultureInfo.InvariantCulture);
}
