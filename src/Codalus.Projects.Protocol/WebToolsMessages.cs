using System.Text.Json.Serialization;

namespace Codalus.Projects.Protocol;

/// <summary>
/// Scaffolding on the build host connection (M15c, ADR 0041, docs/project-protocol.md). The host runs the user's own
/// <c>dotnet aspnet-codegenerator</c> as a child process in the project's folder; every request needs an open, trusted
/// solution, and cancelling one kills its process tree. Scaffolders that need no tool (empty controllers, pages, views,
/// components) go through <c>templates/instantiate</c>.
/// </summary>
public static class ScaffoldMethods
{
    /// <summary>Whether the code generator can run for a project: the tool, the design package, the project's .NET version.</summary>
    public const string Status = "scaffold/status";

    /// <summary>
    /// Installs what scaffolding needs: <c>dotnet-aspnet-codegenerator</c> as a local tool (or restores it) and the
    /// <c>Microsoft.VisualStudio.Web.CodeGeneration.Design</c> package, at the project's .NET major version, and, in a project
    /// that uses EF Core, <c>Microsoft.EntityFrameworkCore.Tools</c> at its EF Core version.
    /// </summary>
    public const string Install = "scaffold/install";

    /// <summary><c>dotnet aspnet-codegenerator &lt;generator&gt; &lt;arguments&gt;</c> in the project's folder.</summary>
    public const string Run = "scaffold/run";

    /// <summary>Host → shell notification: a line of the running code generator.</summary>
    public const string Output = "scaffold/output";
}

public sealed record ScaffoldStatusParams(string Project);

/// <summary>
/// <see cref="ToolVersion"/> is null when the code generator can't run (<see cref="ToolAvailable"/> false);
/// <see cref="ToolSource"/> is <c>local</c> (the tool manifest) or <c>global</c>. <see cref="DesignPackageVersion"/>:
/// the project's <c>Microsoft.VisualStudio.Web.CodeGeneration.Design</c> reference. <see cref="DotnetVersion"/>: the
/// project's target framework version (<c>10.0</c>), which the tool's and the package's versions follow.
/// <see cref="EfProviders"/>: the project's EF Core provider packages (for <c>-dbProvider</c>); <see cref="EfToolsVersion"/>: its
/// <c>Microsoft.EntityFrameworkCore.Tools</c> reference, which the Entity Framework scaffolders need.
/// </summary>
public sealed record ScaffoldStatusResult(
    bool ToolAvailable,
    string? ToolVersion,
    string? ToolSource,
    string? Manifest,
    bool ManifestListsTool,
    string? DesignPackageVersion,
    string? DotnetVersion,
    string[] EfProviders,
    string? EfToolsVersion,
    string? Message);

/// <summary><see cref="Version"/>: null picks the newest stable release of the project's .NET major version.</summary>
public sealed record ScaffoldInstallParams(string Project, string? Version = null);

/// <summary>
/// <see cref="Generator"/>: <c>controller</c>, <c>view</c>, <c>razorpage</c>, <c>area</c>, <c>identity</c>,
/// <c>minimalapi</c>, <c>blazor</c> or <c>blazor-identity</c>; <see cref="Arguments"/> follow it as they are.
/// </summary>
public sealed record ScaffoldRunParams(string Project, string Generator, string[] Arguments);

/// <summary>The files the generator created and those it changed (<c>Program.cs</c>, the project file), and its output.</summary>
public sealed record ScaffoldRunResult(string[] Created, string[] Modified, string Output);

/// <summary>
/// <see cref="Level"/>: <c>info</c> or <c>error</c>; the command line comes as <c>info</c> with a <c>&gt;</c>.
/// <see cref="Source"/>: null for the code generator, <c>wcf</c> for <c>dotnet-svcutil</c> (M42).
/// </summary>
public sealed record ScaffoldOutputParams(string Level, string Line, string? Source = null);

/// <summary>
/// Service references (M15c, ADR 0041): OpenAPI references (<c>&lt;OpenApiReference&gt;</c>, a client generated at
/// build time by NSwag through <c>Microsoft.Extensions.ApiDescription.Client</c>) and gRPC references
/// (<c>&lt;Protobuf&gt;</c>, generated by <c>Grpc.Tools</c>), the items <c>dotnet-openapi</c> writes. The host edits the
/// project file and adds the packages; the document itself is copied or downloaded into the project by the shell.
/// </summary>
public static class ServiceReferenceMethods
{
    public const string List = "serviceReferences/list";

    /// <summary>Adds the item and the packages it needs (those the project doesn't reference yet), then restores.</summary>
    public const string Add = "serviceReferences/add";

    /// <summary>Changes the item's metadata (namespace, class name, generator, options, gRPC services, source URL).</summary>
    public const string Update = "serviceReferences/update";

    /// <summary>Removes the item (and, when asked, sends its document to the trash). The packages stay.</summary>
    public const string Remove = "serviceReferences/remove";
}

public static class ServiceReferenceKinds
{
    public const string OpenApi = "openapi";
    public const string Grpc = "grpc";

    /// <summary>A WCF client generated by <c>dotnet-svcutil</c> into its own folder (M42, <see cref="WcfMethods"/>).</summary>
    public const string Wcf = "wcf";
}

/// <summary>
/// WCF service references (M42, ADR 0066): the user's own <c>dotnet-svcutil</c> (a local or global tool) generates the
/// client into <c>Connected Services/&lt;name&gt;/Reference.cs</c> and adds the <c>System.ServiceModel.*</c> packages;
/// its <c>dotnet-svcutil.params.json</c> and a <c>ConnectedService.json</c> as Visual Studio writes it record the
/// options. Trusted solutions only: the tool builds the project. <c>serviceReferences/list</c> lists them.
/// </summary>
public static class WcfMethods
{
    /// <summary>Whether <c>dotnet-svcutil</c> runs for the project; with <c>install</c>, restores or installs it as a local tool first.</summary>
    public const string Tool = "wcf/tool";

    /// <summary>Generates a new reference from a WSDL document or a service's metadata URL.</summary>
    public const string Add = "wcf/add";

    /// <summary>Generates the reference again: from its recorded inputs, or with new options and inputs when given.</summary>
    public const string Update = "wcf/update";

    /// <summary>Sends the reference's folder to the trash. The packages stay.</summary>
    public const string Remove = "wcf/remove";
}

public sealed record WcfToolParams(string Project, bool Install = false, string? Version = null);

/// <summary><see cref="Source"/>: <c>local</c> or <c>global</c>. <see cref="Message"/>: what is missing, when it isn't available.</summary>
public sealed record WcfToolResult(bool Available, string? Version, string? Source, string? Manifest, bool ManifestListsTool, string? Message);

/// <summary>Which operations the client has: task-based asynchronous ones (the default), both, or synchronous ones only.</summary>
public static class WcfOperationKinds
{
    public const string Async = "async";
    public const string Both = "both";
    public const string Sync = "sync";
}

/// <summary>
/// <c>dotnet-svcutil</c>'s options, as Visual Studio's dialog offers them. <see cref="Serializer"/>: <c>Auto</c>,
/// <c>DataContractSerializer</c> or <c>XmlSerializer</c> (null: Auto). <see cref="CollectionType"/>: e.g.
/// <c>System.Collections.Generic.List`1</c> (null: arrays).
/// </summary>
public sealed record WcfOptions(
    string Operations = WcfOperationKinds.Async,
    string? CollectionType = null,
    bool Internal = false,
    string? Serializer = null,
    bool ReuseTypes = true,
    bool MessageContracts = false,
    bool DataBinding = false);

/// <summary>
/// A reference named <see cref="Name"/> (its folder under <c>Connected Services</c>, and the default namespace).
/// <see cref="Input"/>: a WSDL file or an <c>http(s)</c> metadata address (<c>…?wsdl</c>, or the service's address).
/// </summary>
public sealed record WcfReferenceParams(string Project, string Name, string? Input = null, string? Namespace = null, WcfOptions? Options = null);

/// <summary>The reference's folder, the files the tool created and changed (the project file, for its packages), and its output.</summary>
public sealed record WcfReferenceResult(string Folder, string[] Created, string[] Modified, string Output);

public sealed record WcfRemoveParams(string Project, string Name);

/// <summary>Which services <c>Grpc.Tools</c> generates for a <c>.proto</c> file.</summary>
public static class GrpcServiceKinds
{
    public const string Client = "Client";
    public const string Server = "Server";
    public const string Both = "Both";
    public const string None = "None";
}

public sealed record ServiceReferencesParams(string Project);

/// <summary>
/// A reference: <see cref="Path"/> is the document's full path, <see cref="Include"/> the item as written.
/// <see cref="SourceUrl"/>: where Refresh downloads it from. OpenAPI: <see cref="CodeGenerator"/> (<c>NSwagCSharp</c>,
/// <c>NSwagTypeScript</c>), <see cref="Namespace"/>, <see cref="ClassName"/>, <see cref="Options"/> (NSwag's
/// <c>/Name:value</c> options). gRPC: <see cref="GrpcServices"/>, <see cref="Access"/> (<c>Public</c>, <c>Internal</c>).
/// WCF (M42): <see cref="Path"/> is the reference's <c>ConnectedService.json</c> (or <c>dotnet-svcutil.params.json</c>),
/// <see cref="Include"/> its folder relative to the project, <see cref="ClassName"/> its name, <see cref="Input"/> the
/// WSDL file or address it was generated from, <see cref="Wcf"/> its options.
/// </summary>
public sealed record ServiceReferenceInfo(
    string Kind,
    string Path,
    string Include,
    string? SourceUrl,
    string? Namespace,
    string? ClassName,
    string? CodeGenerator,
    string? Options,
    string? GrpcServices,
    string? Access,
    string? Input = null,
    WcfOptions? Wcf = null);

/// <summary>The project's references, and the packages that generate them it references (id → version).</summary>
public sealed record ServiceReferencesResult(ServiceReferenceInfo[] References, ServiceReferencePackage[] Packages);

public sealed record ServiceReferencePackage(string Id, string? Version);

/// <summary>
/// Adds (or, for <c>serviceReferences/update</c>, changes) a reference to <see cref="File"/>, which must exist.
/// Null metadata isn't written (an update removes it). <see cref="Versions"/>: package versions to use instead of the
/// host's choice (the newest stable version in the global packages folder, else from the sources, else a known one).
/// </summary>
public sealed record ServiceReferenceParams(
    string Project,
    string Kind,
    string File,
    string? SourceUrl = null,
    string? Namespace = null,
    string? ClassName = null,
    string? CodeGenerator = null,
    string? Options = null,
    string? GrpcServices = null,
    string? Access = null,
    bool Restore = true,
    ServiceReferencePackage[]? Versions = null);

/// <summary>The files that changed (the project, <c>Directory.Packages.props</c>) and the packages added, as <c>Id Version</c>.</summary>
public sealed record ServiceReferenceEditResult(string[] ChangedFiles, string[] AddedPackages);

public sealed record ServiceReferenceRemoveParams(string Project, string Kind, string File, bool DeleteFile = false);

