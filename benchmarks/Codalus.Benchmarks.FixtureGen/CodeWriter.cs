using System.Globalization;
using System.Text;

namespace Codalus.Benchmarks.FixtureGen;

/// <summary>
/// Emits varied, compilable C# so that editors and classifiers see a realistic token mix: generics, records,
/// LINQ, async, string escapes, interpolation, XML docs, block comments and preprocessor directives.
/// Output is fully determined by the seed.
/// </summary>
internal sealed class CodeWriter(int seed)
{
    private static readonly string[] s_nouns = ["Order", "Customer", "Invoice", "Widget", "Shipment", "Account", "Ledger", "Route", "Sensor", "Report"];
    private static readonly string[] s_verbs = ["Compute", "Validate", "Merge", "Render", "Resolve", "Collect", "Project", "Normalize"];

    private readonly Random _random = new(seed);
    private readonly StringBuilder _sb = new();
    private int _lines;

    public int Lines => _lines;

    public override string ToString() => _sb.ToString();

    public void Line(string text = "")
    {
        _sb.Append(text).Append('\n');
        _lines++;
    }

    public void FileHeader(string ns)
    {
        Line("// <auto-generated>Codalus benchmark fixture. Do not edit.</auto-generated>");
        Line("#nullable enable");
        Line("using System;");
        Line("using System.Collections.Generic;");
        Line("using System.Linq;");
        Line("using System.Text;");
        Line("using System.Threading;");
        Line("using System.Threading.Tasks;");
        Line();
        Line($"namespace {ns};");
        Line();
    }

    /// <summary>Writes one type (about 60–120 lines).</summary>
    public void Type(int index)
    {
        var noun = s_nouns[index % s_nouns.Length];
        var name = $"{noun}{index}";
        switch (_random.Next(4))
        {
            case 0:
                Line($"/// <summary>Immutable value describing a {noun.ToLowerInvariant()} (#{index}).</summary>");
                Line($"public sealed record {name}Info(int Id, string Name, decimal Amount, DateTime CreatedAt)");
                Line("{");
                Line($"    public static readonly {name}Info Empty = new(0, string.Empty, 0m, DateTime.UnixEpoch);");
                Line("    public bool IsEmpty => Id == 0 && Name.Length == 0;");
                Line("}");
                Line();
                break;
            case 1:
                Line($"public enum {name}State");
                Line("{");
                Line("    None = 0,");
                Line("    Pending = 1,");
                Line("    Active = 2,");
                Line("    Archived = 4,");
                Line("}");
                Line();
                break;
            case 2:
                Line($"public interface I{name}Source<T> where T : notnull");
                Line("{");
                Line($"    IAsyncEnumerable<T> ReadAllAsync(CancellationToken cancellationToken);");
                Line("    bool TryGet(int id, out T? value);");
                Line("}");
                Line();
                break;
            default:
                Line($"public readonly record struct {name}Key(int Shard, long Value);");
                Line();
                break;
        }

        Line($"/// <summary>Service for <see cref=\"{noun}{index}\"/> processing.</summary>");
        Line($"public partial class {name}Service<TItem> : IDisposable where TItem : class");
        Line("{");
        Line($"    private const int MaxBatch = {16 + _random.Next(240)};");
        Line("    private static int s_instances;");
        Line("    private readonly List<TItem> _items = new();");
        Line("    private readonly Dictionary<string, int> _counts = new(StringComparer.Ordinal);");
        Line("    private bool _disposed;");
        Line();
        Line("    public event EventHandler<TItem>? ItemAdded;");
        Line();
        Line("    public int Count => _items.Count;");
        Line();
        Line("    public static int Instances => s_instances;");
        Line();
        var methods = 2 + _random.Next(3);
        for (var m = 0; m < methods; m++)
        {
            Method(m);
        }

        Line("    public void Dispose()");
        Line("    {");
        Line("        if (_disposed)");
        Line("        {");
        Line("            return;");
        Line("        }");
        Line();
        Line("        _disposed = true;");
        Line("        _items.Clear();");
        Line("        GC.SuppressFinalize(this);");
        Line("    }");
        Line("}");
        Line();
    }

    private void Method(int index)
    {
        var verb = s_verbs[_random.Next(s_verbs.Length)];
        switch (_random.Next(4))
        {
            case 0:
                Line($"    /// <summary>{verb}s all items matching <paramref name=\"predicate\"/>.</summary>");
                Line($"    public IReadOnlyList<string> {verb}{index}(Func<TItem, bool> predicate, int take = MaxBatch)");
                Line("    {");
                Line("        var query = from item in _items");
                Line("                    where predicate(item)");
                Line("                    let text = item.ToString() ?? string.Empty");
                Line("                    orderby text.Length descending");
                Line("                    select text.Trim();");
                Line("        return query.Take(take).ToList();");
                Line("    }");
                break;
            case 1:
                Line($"    public async Task<int> {verb}{index}Async(IEnumerable<TItem> source, CancellationToken cancellationToken)");
                Line("    {");
                Line("        var added = 0;");
                Line("        foreach (var chunk in source.Chunk(MaxBatch))");
                Line("        {");
                Line("            cancellationToken.ThrowIfCancellationRequested();");
                Line("            await Task.Yield();");
                Line("            foreach (var item in chunk)");
                Line("            {");
                Line("                _items.Add(item);");
                Line("                ItemAdded?.Invoke(this, item);");
                Line("                added++;");
                Line("            }");
                Line("        }");
                Line();
                Line("        Interlocked.Add(ref s_instances, added);");
                Line("        return added;");
                Line("    }");
                break;
            case 2:
                var number = (_random.NextDouble() * 1000).ToString("F3", CultureInfo.InvariantCulture);
                Line($"    public string {verb}{index}(string key, double factor = {number})");
                Line("    {");
                Line("        /* Formats a report line.");
                Line("           Uses interpolation, escapes and verbatim strings. */");
                Line("        var builder = new StringBuilder();");
                Line("        builder.Append($\"{key,-12}\\t{factor:F2}\\n\");");
                Line("        builder.Append(@\"C:\\data\\reports\\\").Append(key).Append(\".txt\");");
                Line("        _counts[key] = _counts.TryGetValue(key, out var n) ? n + 1 : 1;");
                Line("#if DEBUG");
                Line("        builder.Append(\" [debug]\");");
                Line("#endif");
                Line("        return builder.ToString();");
                Line("    }");
                break;
            default:
                Line($"    public static TResult {verb}{index}<TResult>(TItem item, Func<TItem, TResult> selector)");
                Line("        where TResult : IComparable<TResult>");
                Line("    {");
                Line("        ArgumentNullException.ThrowIfNull(item);");
                Line("        var result = selector(item);");
                Line("        return result switch");
                Line("        {");
                Line("            null => throw new InvalidOperationException(\"selector returned null\"),");
                Line("            _ => result,");
                Line("        };");
                Line("    }");
                break;
        }

        Line();
    }
}
