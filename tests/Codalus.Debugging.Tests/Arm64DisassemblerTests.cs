    /// <summary>
    /// Any word at all decodes without throwing: to an instruction (a lowercase mnemonic, single spaces) or to
    /// <c>.inst</c> with the word itself. Random words, and words forced into each of the sixteen top-level classes so
    /// the sparse ones are reached.
    /// </summary>
    [Fact]
    public void Any_word_decodes_or_is_inst_and_never_throws()
    {
        var random = new Random(58);
        var decoded = 0;
        for (var n = 0; n < 400_000; n++)
        {
            var word = (uint)random.NextInt64(0, 1L << 32);
            if (n % 2 == 1)
            {
                word = (word & ~(0xFu << 25)) | ((uint)(n / 2 % 16) << 25);
            }

            var text = Arm64Disassembler.Decode(word, Address + (ulong)(n * 4));
            if (text.StartsWith(".inst", StringComparison.Ordinal))
            {
                Assert.Equal(".inst 0x" + word.ToString("x8", CultureInfo.InvariantCulture), text);
                continue;
            }

            decoded++;
            Assert.True(
                text.Length > 0 && char.IsAsciiLetterLower(text[0]) && !text.Contains("  ", StringComparison.Ordinal) && text[^1] != ' ' && text.All(c => c is >= ' ' and <= '~'),
                $"0x{word:x8} decodes as '{text}'");
        }

        // About three words in ten are instructions it decodes; far fewer would mean it had stopped decoding.
        Assert.InRange(decoded, 100_000, 200_000);
    }

    /// <summary>The fields that index tables at their extremes, in every class: register numbers, conditions and immediates all ones, all zeros and alternating.</summary>
    [Fact]
    public void Extreme_fields_in_every_class_never_throw()
    {
        uint[] fields = [0, 0x1FFFFF, 0x1F, 0x3E0, 0x1F0000, 0xFC00, 0x1F03FF, 0x00FC1F, 0x155555, 0x0AAAAA];
        for (uint high = 0; high < 1 << 11; high++)
        {
            foreach (var low in fields)
            {
                var word = (high << 21) | low;
                var text = Arm64Disassembler.Decode(word, ulong.MaxValue - 3);
                Assert.True(
                    text.Length > 0 && (!text.Contains(".inst", StringComparison.Ordinal) || text == ".inst 0x" + word.ToString("x8", CultureInfo.InvariantCulture)),
                    $"0x{word:x8} decodes as '{text}'");
            }
        }
    }

    /// <summary>Only the PC-relative instructions read the address: everything else is the same text wherever it sits.</summary>
    [Fact]
    public void Only_pc_relative_instructions_depend_on_the_address()
    {
        string[] relative = ["b", "bl", "cbz", "cbnz", "tbz", "tbnz", "adr", "adrp", "ldr", "ldrsw", "prfm"];
        var random = new Random(94);
        for (var n = 0; n < 200_000; n++)
        {
            var word = (uint)random.NextInt64(0, 1L << 32);
            var here = Arm64Disassembler.Decode(word, 0x1000);
            var there = Arm64Disassembler.Decode(word, 0xFFFF_8000_0000_2468);
            if (here != there)
            {
                var mnemonic = here.Split(' ')[0];
                Assert.True(relative.Contains(mnemonic) || mnemonic.StartsWith("b.", StringComparison.Ordinal), $"0x{word:x8}: '{here}' and '{there}'");
            }
        }
    }
